/**
 * Regenerates `src/features-v2/beastforms/srd-data.js` from the SRD JSON.
 * Run from repo root: node scripts/generate-beastform-srd-data.mjs
 */
import { readFileSync, writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const jsonPath = join(root, 'daggerheart-srd', '.build', '03_json', 'beastforms.json');
const outPath = join(root, 'src', 'features-v2', 'beastforms', 'srd-data.js');

function slugify(name) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

function parseFeatureName(rawName) {
  const lastDash = rawName.lastIndexOf(' - ');
  if (lastDash >= 0) {
    const name = rawName.slice(0, lastDash).trim();
    const typeRaw = rawName.slice(lastDash + 3).toLowerCase().trim();
    const type = ['action', 'reaction', 'passive'].includes(typeRaw) ? typeRaw : 'passive';
    return { name, type };
  }
  return { name: rawName.trim(), type: 'passive' };
}

function parseFeatures(featureArr, parentId) {
  if (!Array.isArray(featureArr)) return [];
  return featureArr.map((f) => {
    const { name, type } = parseFeatureName(f.name || '');
    return {
      id: `${parentId}-feat-${slugify(name)}`,
      name,
      type,
      description: f.text || '',
    };
  });
}

function makeId(name) {
  return `srd-bst-${slugify(name)}`;
}

function normalize(raw) {
  const id = makeId(raw.name || '');
  return {
    id,
    name: raw.name || '',
    tier: parseInt(raw.tier, 10) || 1,
    examples: raw.examples || '',
    trait_bonus: raw.trait_bonus || '',
    evasion_bonus: raw.evasion_bonus || '',
    attack: raw.attack || '',
    advantages: raw.advantages || '',
    features: parseFeatures(raw.feature, id),
  };
}

const raw = JSON.parse(readFileSync(jsonPath, 'utf8').replace(/^\uFEFF/, ''));
const items = raw.map(normalize);
const out = `/**
 * AUTO-GENERATED by scripts/generate-beastform-srd-data.mjs — do not edit by hand.
 * Source: daggerheart-srd/.build/03_json/beastforms.json
 * Regenerate: \`node scripts/generate-beastform-srd-data.mjs\`
 */
export const BEASTFORM_ITEMS = ${JSON.stringify(items, null, 2)};
`;
writeFileSync(outPath, out);
console.log('Wrote', items.length, 'entries to', outPath);
